-- Grandes Operações: projetos do portal, stakeholders, acompanhamento das etapas e cadastro de
-- atividades pela tela.
--   * Projetos do portal: os do cadastro de projetos cujo GP é o gerente de Grandes Operações
--     (go_config) entram no Hub sozinhos, com o cliente pela razão social. Os do Hub antigo continuam.
--   * Stakeholders: as pessoas do projeto (nome e empresa). A atividade tem um ou mais como
--     responsáveis, e o texto "responsavel" passa a ser montado a partir deles (atividade antiga,
--     sem stakeholder, mantém o texto da planilha).
--   * Acompanhamento da etapa: histórico com data, hora e quem escreveu; não se edita nem se apaga.
--   * go_salvar_atividade: cria ou edita a atividade com a etapa (ou uma etapa nova), responsáveis,
--     predecessoras e dependentes numa gravação só (um ciclo desfaz tudo).

-- ---------- Projetos do portal ----------

ALTER TABLE public.go_projetos ADD COLUMN IF NOT EXISTS project_id uuid UNIQUE REFERENCES public.projects (id) ON DELETE SET NULL;

-- Uma linha só: o Gerente de Projetos cujos projetos do portal entram no Hub
CREATE TABLE IF NOT EXISTS public.go_config (
  id             boolean     PRIMARY KEY DEFAULT true CHECK (id),
  gerente_id     uuid        REFERENCES public.team_members (id) ON DELETE SET NULL,
  atualizado_em  timestamptz NOT NULL DEFAULT now(),
  atualizado_por uuid
);
INSERT INTO public.go_config (id) VALUES (true) ON CONFLICT (id) DO NOTHING;

-- ---------- Stakeholders e responsáveis ----------

CREATE TABLE IF NOT EXISTS public.go_stakeholders (
  id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id integer      NOT NULL REFERENCES public.go_projetos (id) ON DELETE CASCADE,
  nome       varchar(150) NOT NULL CHECK (btrim(nome) <> ''),
  empresa    varchar(100) NOT NULL DEFAULT '',
  ordem      integer      NOT NULL DEFAULT 0,
  criado_em  timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS go_uq_stakeholders_nome ON public.go_stakeholders (projeto_id, lower(btrim(nome)));

-- Responsáveis da atividade; tirar o stakeholder do projeto tira ele das atividades
CREATE TABLE IF NOT EXISTS public.go_atividade_stakeholders (
  atividade_id   integer NOT NULL REFERENCES public.go_atividades (id) ON DELETE CASCADE,
  stakeholder_id integer NOT NULL REFERENCES public.go_stakeholders (id) ON DELETE CASCADE,
  PRIMARY KEY (atividade_id, stakeholder_id)
);
CREATE INDEX IF NOT EXISTS go_ix_atv_stk_stakeholder ON public.go_atividade_stakeholders (stakeholder_id);

-- o texto junta os stakeholders ("Ana Lima (ENBI) + João (Transdata)"): pode passar de 150
ALTER TABLE public.go_atividades ALTER COLUMN responsavel TYPE text;

-- ---------- Acompanhamento das etapas ----------

CREATE TABLE IF NOT EXISTS public.go_etapa_observacoes (
  id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etapa_id   integer      NOT NULL REFERENCES public.go_etapas (id) ON DELETE CASCADE,
  texto      text         NOT NULL CHECK (btrim(texto) <> ''),
  criado_em  timestamptz  NOT NULL DEFAULT now(),
  autor_id   uuid,
  autor_nome varchar(150) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS go_ix_obs_etapa ON public.go_etapa_observacoes (etapa_id, criado_em);

-- ---------- Regras (gatilhos) ----------

-- 5) projeto do portal: entra no Hub quando o GP é o gerente de Grandes Operações; sai se mudar de
--    GP antes de ter algo registrado. A situação acompanha o status do portal.
CREATE OR REPLACE FUNCTION public.go_sincronizar_projeto(_project_id uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  p      record;
  v_ger  uuid := (SELECT gerente_id FROM public.go_config WHERE id);
  v_go   integer;
  v_cli  integer;
  v_sit  text;
  v_nome text;
BEGIN
  SELECT id, tenant_id, company_name, city, state, status, manager_id INTO p FROM public.projects WHERE id = _project_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT id, cliente_id INTO v_go, v_cli FROM public.go_projetos WHERE project_id = p.id;
  v_sit := CASE p.status::text WHEN 'encerrado' THEN 'encerrado' WHEN 'suspenso' THEN 'pausado' ELSE 'ativo' END;

  IF v_ger IS NOT NULL AND p.manager_id = v_ger AND p.tenant_id = 'a2f1c8e0-0000-4000-8000-000000000001'::uuid THEN
    IF v_go IS NOT NULL THEN
      UPDATE public.go_projetos SET situacao = v_sit WHERE id = v_go AND situacao <> v_sit;
      RETURN;
    END IF;
    v_nome := left(btrim(coalesce(p.company_name, '')), 150);
    IF v_nome = '' THEN RETURN; END IF;
    SELECT id INTO v_cli FROM public.go_clientes WHERE lower(btrim(nome)) = lower(v_nome) ORDER BY id LIMIT 1;
    IF v_cli IS NULL THEN
      INSERT INTO public.go_clientes (nome, "local", ordem)
      VALUES (v_nome, left(concat_ws('/', nullif(btrim(p.city), ''), p.state::text), 150),
              coalesce((SELECT max(ordem) + 1 FROM public.go_clientes), 1))
      RETURNING id INTO v_cli;
    END IF;
    INSERT INTO public.go_projetos (cliente_id, nome, situacao, project_id, ordem)
    VALUES (v_cli, v_nome, v_sit, p.id, coalesce((SELECT max(ordem) + 1 FROM public.go_projetos WHERE cliente_id = v_cli), 1));
  ELSIF v_go IS NOT NULL THEN
    DELETE FROM public.go_projetos g WHERE g.id = v_go
      AND NOT EXISTS (SELECT 1 FROM public.go_atividades a WHERE a.projeto_id = g.id)
      AND NOT EXISTS (SELECT 1 FROM public.go_etapas e WHERE e.projeto_id = g.id)
      AND NOT EXISTS (SELECT 1 FROM public.go_stakeholders s WHERE s.projeto_id = g.id);
    IF FOUND THEN
      DELETE FROM public.go_clientes c WHERE c.id = v_cli AND NOT EXISTS (SELECT 1 FROM public.go_projetos x WHERE x.cliente_id = c.id);
    END IF;
  END IF;
END $$;
REVOKE ALL ON FUNCTION public.go_sincronizar_projeto(uuid) FROM PUBLIC, anon, authenticated;

-- o cadastro do projeto nunca é barrado pelo Hub
CREATE OR REPLACE FUNCTION public.go_tg_projeto_portal() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  BEGIN
    PERFORM public.go_sincronizar_projeto(NEW.id);
  EXCEPTION WHEN others THEN
    RAISE WARNING 'Grandes Operações: o projeto % não foi sincronizado com o Hub: %', NEW.id, SQLERRM;
  END;
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS go_projeto_portal ON public.projects;
CREATE TRIGGER go_projeto_portal AFTER INSERT OR UPDATE OF manager_id, status ON public.projects
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_projeto_portal();

-- 6) responsável da atividade: stakeholder do mesmo projeto
CREATE OR REPLACE FUNCTION public.go_tg_responsavel_valido() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF (SELECT projeto_id FROM public.go_atividades WHERE id = NEW.atividade_id)
     IS DISTINCT FROM (SELECT projeto_id FROM public.go_stakeholders WHERE id = NEW.stakeholder_id) THEN
    RAISE EXCEPTION 'O responsável precisa ser um stakeholder do mesmo projeto da atividade.' USING errcode = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS go_responsavel_valido ON public.go_atividade_stakeholders;
CREATE TRIGGER go_responsavel_valido BEFORE INSERT OR UPDATE ON public.go_atividade_stakeholders
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_responsavel_valido();

-- 7) o texto "responsavel" da atividade sai dos stakeholders dela
CREATE OR REPLACE FUNCTION public.go_recalcular_responsavel(_atividade integer) RETURNS void
LANGUAGE sql SET search_path = public AS $$
  UPDATE public.go_atividades a
     SET responsavel = coalesce((
       SELECT string_agg(s.nome || CASE WHEN btrim(s.empresa) <> '' THEN ' (' || btrim(s.empresa) || ')' ELSE '' END, ' + ' ORDER BY s.ordem, s.id)
         FROM public.go_atividade_stakeholders l JOIN public.go_stakeholders s ON s.id = l.stakeholder_id
        WHERE l.atividade_id = a.id), '')
   WHERE a.id = _atividade;
$$;

CREATE OR REPLACE FUNCTION public.go_tg_responsaveis_mudaram() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  PERFORM public.go_recalcular_responsavel(coalesce(NEW.atividade_id, OLD.atividade_id));
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS go_responsaveis_mudaram ON public.go_atividade_stakeholders;
CREATE TRIGGER go_responsaveis_mudaram AFTER INSERT OR DELETE ON public.go_atividade_stakeholders
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_responsaveis_mudaram();

CREATE OR REPLACE FUNCTION public.go_tg_stakeholder_mudou() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
DECLARE x integer;
BEGIN
  FOR x IN SELECT atividade_id FROM public.go_atividade_stakeholders WHERE stakeholder_id = NEW.id LOOP
    PERFORM public.go_recalcular_responsavel(x);
  END LOOP;
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS go_stakeholder_mudou ON public.go_stakeholders;
CREATE TRIGGER go_stakeholder_mudou AFTER UPDATE OF nome, empresa, ordem ON public.go_stakeholders
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_stakeholder_mudou();

-- 8) acompanhamento: data, hora e autor vêm da sessão
CREATE OR REPLACE FUNCTION public.go_tg_obs_etapa_autor() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  NEW.criado_em := now();
  NEW.autor_id := auth.uid();
  NEW.autor_nome := left(coalesce((SELECT nullif(btrim(full_name), '') FROM public.profiles WHERE user_id = auth.uid() LIMIT 1), ''), 150);
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS go_obs_etapa_autor ON public.go_etapa_observacoes;
CREATE TRIGGER go_obs_etapa_autor BEFORE INSERT ON public.go_etapa_observacoes
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_obs_etapa_autor();

-- ---------- Gravações pela tela ----------

-- Escolhe o gerente de Grandes Operações e sincroniza os projetos do portal. Devolve quantos
-- projetos do portal ficaram no Hub.
CREATE OR REPLACE FUNCTION public.go_definir_gerente(_gerente uuid) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id uuid;
BEGIN
  IF NOT public.go_pode('edit') THEN
    RAISE EXCEPTION 'Seu acesso não permite mudar o Hub.' USING errcode = 'insufficient_privilege';
  END IF;
  IF _gerente IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.team_members WHERE id = _gerente AND role = 'gerente_projetos'
      AND tenant_id = 'a2f1c8e0-0000-4000-8000-000000000001'::uuid) THEN
    RAISE EXCEPTION 'Escolha um Gerente de Projetos da Equipe da Transdata.' USING errcode = 'check_violation';
  END IF;
  UPDATE public.go_config SET gerente_id = _gerente, atualizado_em = now(), atualizado_por = auth.uid() WHERE id;
  FOR v_id IN
    SELECT p.id FROM public.projects p
     WHERE p.tenant_id = 'a2f1c8e0-0000-4000-8000-000000000001'::uuid
       AND (p.manager_id = _gerente OR EXISTS (SELECT 1 FROM public.go_projetos g WHERE g.project_id = p.id))
  LOOP
    PERFORM public.go_sincronizar_projeto(v_id);
  END LOOP;
  RETURN (SELECT count(*) FROM public.go_projetos WHERE project_id IS NOT NULL)::integer;
END $$;
REVOKE ALL ON FUNCTION public.go_definir_gerente(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.go_definir_gerente(uuid) TO authenticated;

-- Cria (sem id) ou edita a atividade. _a: id, projeto_id, etapa_id ou etapa_nova, codigo, titulo,
-- objetivo, duracao, data_prevista, predecessoras[], dependentes[] e, quando vier, responsaveis[]
-- (ids de stakeholders). Roda com o acesso de quem chama (RLS do Hub).
CREATE OR REPLACE FUNCTION public.go_salvar_atividade(_a jsonb) RETURNS integer
LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  v_id    integer := nullif(_a->>'id', '')::integer;
  v_proj  integer := (_a->>'projeto_id')::integer;
  v_etapa integer := nullif(_a->>'etapa_id', '')::integer;
  v_nova  text    := nullif(btrim(coalesce(_a->>'etapa_nova', '')), '');
  v_preds integer[] := ARRAY(SELECT DISTINCT x::integer FROM jsonb_array_elements_text(coalesce(_a->'predecessoras', '[]'::jsonb)) x);
  v_deps  integer[] := ARRAY(SELECT DISTINCT x::integer FROM jsonb_array_elements_text(coalesce(_a->'dependentes', '[]'::jsonb)) x);
  v_resp  integer[] := ARRAY(SELECT DISTINCT x::integer FROM jsonb_array_elements_text(coalesce(_a->'responsaveis', '[]'::jsonb)) x);
BEGIN
  IF NOT public.go_pode('edit') THEN
    RAISE EXCEPTION 'Seu acesso não permite editar o Hub.' USING errcode = 'insufficient_privilege';
  END IF;
  IF v_nova IS NOT NULL THEN
    INSERT INTO public.go_etapas (projeto_id, nome, ordem)
    VALUES (v_proj, left(v_nova, 150), coalesce((SELECT max(ordem) + 1 FROM public.go_etapas WHERE projeto_id = v_proj), 1))
    RETURNING id INTO v_etapa;
  END IF;
  IF v_etapa IS NULL THEN
    RAISE EXCEPTION 'Escolha a etapa da atividade.' USING errcode = 'check_violation';
  END IF;

  IF v_id IS NULL THEN
    INSERT INTO public.go_atividades (projeto_id, etapa_id, codigo, titulo, objetivo, duracao, data_prevista, ordem)
    VALUES (v_proj, v_etapa, btrim(_a->>'codigo'), btrim(_a->>'titulo'), coalesce(_a->>'objetivo', ''),
            left(coalesce(_a->>'duracao', ''), 50), nullif(_a->>'data_prevista', '')::date,
            coalesce((SELECT max(ordem) + 1 FROM public.go_atividades WHERE projeto_id = v_proj), 1))
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.go_atividades
       SET etapa_id = v_etapa, codigo = btrim(_a->>'codigo'), titulo = btrim(_a->>'titulo'), objetivo = coalesce(_a->>'objetivo', ''),
           duracao = left(coalesce(_a->>'duracao', ''), 50), data_prevista = nullif(_a->>'data_prevista', '')::date
     WHERE id = v_id AND projeto_id = v_proj;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'A atividade não foi encontrada neste projeto.' USING errcode = 'no_data_found';
    END IF;
  END IF;

  -- vem antes desta / depende desta: o gatilho das predecessoras barra ciclo e outro projeto
  DELETE FROM public.go_predecessoras WHERE atividade_id = v_id AND predecessora_id <> ALL (v_preds);
  INSERT INTO public.go_predecessoras (atividade_id, predecessora_id)
    SELECT v_id, x FROM unnest(v_preds) x
     WHERE NOT EXISTS (SELECT 1 FROM public.go_predecessoras WHERE atividade_id = v_id AND predecessora_id = x);
  DELETE FROM public.go_predecessoras WHERE predecessora_id = v_id AND atividade_id <> ALL (v_deps);
  INSERT INTO public.go_predecessoras (atividade_id, predecessora_id)
    SELECT x, v_id FROM unnest(v_deps) x
     WHERE NOT EXISTS (SELECT 1 FROM public.go_predecessoras WHERE atividade_id = x AND predecessora_id = v_id);

  -- sem a lista, a atividade antiga mantém o texto da planilha
  IF _a ? 'responsaveis' THEN
    DELETE FROM public.go_atividade_stakeholders WHERE atividade_id = v_id AND stakeholder_id <> ALL (v_resp);
    INSERT INTO public.go_atividade_stakeholders (atividade_id, stakeholder_id)
      SELECT v_id, x FROM unnest(v_resp) x
       WHERE NOT EXISTS (SELECT 1 FROM public.go_atividade_stakeholders WHERE atividade_id = v_id AND stakeholder_id = x);
  END IF;
  RETURN v_id;
END $$;
REVOKE ALL ON FUNCTION public.go_salvar_atividade(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.go_salvar_atividade(jsonb) TO authenticated;

