-- Gestão Operacional · Grandes Operações: o Hub de projetos do departamento de Grandes Operações,
-- que rodava em outro sistema (pacote "Painel-Projetos-Supabase", scripts 01 e 02), no portal.
-- Hierarquia: cliente → projeto → etapa → atividade (com predecessoras e observações).
--
-- Tabelas, valores de referência e regras do banco iguais às do pacote (prefixo go_), para a
-- carga dos dados do pacote (03) rodar como está. O que muda no portal:
--   * sem go_usuarios / go_niveis: quem vê e quem edita vem das permissões do portal
--     (módulo "grandes_operacoes": Ver / Editar). O portal tem outras empresas, então só
--     usuários da Transdata entram (o Super Admin vê e edita);
--   * a carga dos dados NÃO está aqui (o repositório é público): roda à parte, do pacote local.

-- ---------- Tabelas de referência ----------

-- Situação do projeto: ativo, pausado, encerrado
CREATE TABLE IF NOT EXISTS public.go_situacoes (
  codigo varchar(20) PRIMARY KEY,
  nome   varchar(50) NOT NULL,
  ordem  integer     NOT NULL DEFAULT 0
);

-- Status da atividade: espera, andamento, concluido, removido
CREATE TABLE IF NOT EXISTS public.go_status_atividade (
  codigo varchar(20) PRIMARY KEY,
  nome   varchar(50) NOT NULL,
  ordem  integer     NOT NULL DEFAULT 0
);

INSERT INTO public.go_situacoes (codigo, nome, ordem) VALUES
  ('ativo', 'Ativo', 1), ('pausado', 'Pausado', 2), ('encerrado', 'Encerrado', 3)
ON CONFLICT (codigo) DO NOTHING;

-- Exatamente estes quatro. Não existe "bloqueado" (decisão do departamento).
INSERT INTO public.go_status_atividade (codigo, nome, ordem) VALUES
  ('espera', 'Em espera', 1), ('andamento', 'Em andamento', 2), ('concluido', 'Concluído', 3), ('removido', 'Removido', 4)
ON CONFLICT (codigo) DO NOTHING;

-- ---------- Cadastros ----------

CREATE TABLE IF NOT EXISTS public.go_clientes (
  id        integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome      varchar(150) NOT NULL,
  "local"   varchar(150) NOT NULL DEFAULT '',
  ordem     integer      NOT NULL DEFAULT 0,
  criado_em timestamptz  NOT NULL DEFAULT now()
);

-- Cliente com projeto não pode ser apagado (on delete restrict)
CREATE TABLE IF NOT EXISTS public.go_projetos (
  id                    integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id            integer      NOT NULL REFERENCES public.go_clientes (id) ON DELETE RESTRICT,
  nome                  varchar(150) NOT NULL,
  curto                 varchar(80)  NOT NULL DEFAULT '',
  situacao              varchar(20)  NOT NULL DEFAULT 'ativo' REFERENCES public.go_situacoes (codigo),
  sequenciar_automatico boolean      NOT NULL DEFAULT true,
  ordem                 integer      NOT NULL DEFAULT 0,
  criado_em             timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS go_ix_projetos_cliente ON public.go_projetos (cliente_id);

-- Nomes individuais do projeto (ex.: Transdata, o cliente, um parceiro); não repete no projeto
CREATE TABLE IF NOT EXISTS public.go_projeto_responsaveis (
  id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id integer      NOT NULL REFERENCES public.go_projetos (id) ON DELETE CASCADE,
  nome       varchar(100) NOT NULL,
  ordem      integer      NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS go_uq_resp_projeto_nome ON public.go_projeto_responsaveis (projeto_id, lower(nome));

CREATE TABLE IF NOT EXISTS public.go_etapas (
  id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id integer      NOT NULL REFERENCES public.go_projetos (id) ON DELETE CASCADE,
  nome       varchar(150) NOT NULL,
  ordem      integer      NOT NULL DEFAULT 0,
  -- usado pela atividade para garantir que a etapa é do mesmo projeto
  CONSTRAINT go_uq_etapas_id_projeto UNIQUE (id, projeto_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS go_uq_etapas_projeto_nome ON public.go_etapas (projeto_id, lower(nome));

-- Projeto com atividade não pode ser apagado; a etapa tem que ser do mesmo projeto (chave dupla)
CREATE TABLE IF NOT EXISTS public.go_atividades (
  id             integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_origem      varchar(50)  NULL UNIQUE,                 -- id no painel antigo (rastreio da importação)
  projeto_id     integer      NOT NULL REFERENCES public.go_projetos (id) ON DELETE RESTRICT,
  etapa_id       integer      NOT NULL,
  codigo         varchar(30)  NOT NULL,                    -- ex.: 1.1.1, 1.4.6.1
  titulo         varchar(255) NOT NULL,
  responsavel    varchar(150) NOT NULL DEFAULT '',         -- texto livre ("Transdata + Cliente")
  objetivo       text         NOT NULL DEFAULT '',
  duracao        varchar(50)  NOT NULL DEFAULT '',         -- texto livre ("2 dias"); vale o 1º número
  data_prevista  date         NULL,
  data_realizada date         NULL,
  status         varchar(20)  NOT NULL DEFAULT 'espera' REFERENCES public.go_status_atividade (codigo),
  ordem          integer      NOT NULL DEFAULT 0,
  atualizado_em  timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT go_fk_atividades_etapa FOREIGN KEY (etapa_id, projeto_id) REFERENCES public.go_etapas (id, projeto_id) ON DELETE RESTRICT,
  CONSTRAINT go_uq_atividades_codigo UNIQUE (projeto_id, codigo),
  CONSTRAINT go_ck_atividades_codigo CHECK (codigo ~ '^[0-9]+(\.[0-9]+)*$'),
  CONSTRAINT go_ck_atividades_titulo CHECK (btrim(titulo) <> '')
);

-- "atividade_id só começa depois de predecessora_id". Apagar uma atividade da qual outra
-- depende é recusado pelo banco.
CREATE TABLE IF NOT EXISTS public.go_predecessoras (
  atividade_id    integer NOT NULL REFERENCES public.go_atividades (id) ON DELETE CASCADE,
  predecessora_id integer NOT NULL REFERENCES public.go_atividades (id) ON DELETE RESTRICT,
  PRIMARY KEY (atividade_id, predecessora_id),
  CONSTRAINT go_ck_pred_nao_ela_mesma CHECK (atividade_id <> predecessora_id)
);
CREATE INDEX IF NOT EXISTS go_ix_pred_predecessora ON public.go_predecessoras (predecessora_id);

-- data pode ficar vazia: metade das observações do painel antigo não tem data
CREATE TABLE IF NOT EXISTS public.go_observacoes (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atividade_id integer NOT NULL REFERENCES public.go_atividades (id) ON DELETE CASCADE,
  data         date    NULL,
  texto        text    NOT NULL CHECK (btrim(texto) <> ''),
  ordem        integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS go_ix_obs_atividade ON public.go_observacoes (atividade_id);

-- ---------- Regras de negócio (gatilhos, iguais aos do pacote) ----------
-- Durante a carga, go.carga = 'sim' desliga só o "marcar atividade como atualizada".

-- 1) atualizado_em: toda alteração na atividade atualiza a data
CREATE OR REPLACE FUNCTION public.go_tg_atividade_atualizada() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  NEW.atualizado_em := now();
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS go_atividade_atualizada ON public.go_atividades;
CREATE TRIGGER go_atividade_atualizada BEFORE UPDATE ON public.go_atividades
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_atividade_atualizada();

-- 2) mexer em observação ou predecessora também conta como alteração da atividade
CREATE OR REPLACE FUNCTION public.go_tg_marcar_atividade() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  alvo integer := coalesce(NEW.atividade_id, OLD.atividade_id);
BEGIN
  IF coalesce(current_setting('go.carga', true), '') <> 'sim' THEN
    UPDATE public.go_atividades SET atualizado_em = now() WHERE id = alvo;
  END IF;
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS go_obs_marca_atividade ON public.go_observacoes;
CREATE TRIGGER go_obs_marca_atividade AFTER INSERT OR UPDATE OR DELETE ON public.go_observacoes
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_marcar_atividade();
DROP TRIGGER IF EXISTS go_pred_marca_atividade ON public.go_predecessoras;
CREATE TRIGGER go_pred_marca_atividade AFTER INSERT OR UPDATE OR DELETE ON public.go_predecessoras
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_marcar_atividade();

-- 3) projeto encerrado não recebe atividade nova (as que já existem continuam editáveis)
CREATE OR REPLACE FUNCTION public.go_tg_atividade_nova() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.go_projetos WHERE id = NEW.projeto_id AND situacao = 'encerrado') THEN
    RAISE EXCEPTION 'Este projeto está encerrado e não recebe atividade nova.' USING errcode = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS go_atividade_nova ON public.go_atividades;
CREATE TRIGGER go_atividade_nova BEFORE INSERT ON public.go_atividades
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_atividade_nova();

-- 4) predecessora do mesmo projeto e sem ciclo (nem indireto); trava o projeto enquanto confere
CREATE OR REPLACE FUNCTION public.go_tg_predecessora_valida() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  proj_ativ integer;
  proj_pred integer;
  caminho   text;
BEGIN
  SELECT projeto_id INTO proj_ativ FROM public.go_atividades WHERE id = NEW.atividade_id;
  SELECT projeto_id INTO proj_pred FROM public.go_atividades WHERE id = NEW.predecessora_id;
  IF proj_ativ IS DISTINCT FROM proj_pred THEN
    RAISE EXCEPTION 'A predecessora precisa ser do mesmo projeto da atividade.' USING errcode = 'check_violation';
  END IF;

  PERFORM 1 FROM public.go_projetos WHERE id = proj_ativ FOR UPDATE;

  -- partindo da predecessora, segue as predecessoras dela; se chegar na própria atividade,
  -- a ligação nova fecharia um ciclo
  WITH RECURSIVE cadeia(id, trilha) AS (
    SELECT NEW.predecessora_id, ARRAY[NEW.predecessora_id]
    UNION ALL
    SELECT p.predecessora_id, c.trilha || p.predecessora_id
      FROM cadeia c
      JOIN public.go_predecessoras p ON p.atividade_id = c.id
     WHERE NOT p.predecessora_id = ANY (c.trilha)
  )
  SELECT string_agg(a.codigo, ' → ' ORDER BY t.pos)
    INTO caminho
    FROM (SELECT trilha FROM cadeia WHERE id = NEW.atividade_id LIMIT 1) c,
         unnest(c.trilha) WITH ORDINALITY AS t(id, pos)
    JOIN public.go_atividades a ON a.id = t.id;

  IF caminho IS NOT NULL THEN
    RAISE EXCEPTION 'Essa ligação criaria um ciclo: %', caminho USING errcode = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS go_predecessora_valida ON public.go_predecessoras;
CREATE TRIGGER go_predecessora_valida BEFORE INSERT OR UPDATE ON public.go_predecessoras
  FOR EACH ROW EXECUTE FUNCTION public.go_tg_predecessora_valida();

-- ---------- Acesso: permissões do portal, só Transdata ----------

-- _acao: 'view' (ver e exportar) ou 'edit' (gravar). Super Admin: sempre; os demais precisam ser
-- da Transdata e ter a permissão no módulo "grandes_operacoes" (admin da Transdata já tem).
CREATE OR REPLACE FUNCTION public.go_pode(_acao text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT auth.uid() IS NOT NULL AND (
    public.has_role(auth.uid(), 'super_admin')
    OR (public.get_my_tenant_id() = 'a2f1c8e0-0000-4000-8000-000000000001'::uuid
        AND public.has_permission(auth.uid(), 'grandes_operacoes', _acao))
  )
$$;
REVOKE ALL ON FUNCTION public.go_pode(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.go_pode(text) TO authenticated;

REVOKE ALL ON public.go_situacoes, public.go_status_atividade, public.go_clientes, public.go_projetos,
  public.go_projeto_responsaveis, public.go_etapas, public.go_atividades, public.go_predecessoras, public.go_observacoes
FROM anon;
-- referências: só leitura pela tela (mudança nelas é por migração)
REVOKE ALL ON public.go_situacoes, public.go_status_atividade FROM authenticated;
GRANT SELECT ON public.go_situacoes, public.go_status_atividade TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.go_clientes, public.go_projetos, public.go_projeto_responsaveis,
  public.go_etapas, public.go_atividades, public.go_predecessoras, public.go_observacoes TO authenticated;
GRANT ALL ON public.go_situacoes, public.go_status_atividade, public.go_clientes, public.go_projetos,
  public.go_projeto_responsaveis, public.go_etapas, public.go_atividades, public.go_predecessoras, public.go_observacoes TO service_role;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['go_situacoes', 'go_status_atividade', 'go_clientes', 'go_projetos', 'go_projeto_responsaveis',
                           'go_etapas', 'go_atividades', 'go_predecessoras', 'go_observacoes']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS go_ver ON public.%I', t);
    EXECUTE format('CREATE POLICY go_ver ON public.%I FOR SELECT TO authenticated USING (public.go_pode(''view''))', t);
    IF t NOT IN ('go_situacoes', 'go_status_atividade') THEN
      EXECUTE format('DROP POLICY IF EXISTS go_editar ON public.%I', t);
      EXECUTE format('CREATE POLICY go_editar ON public.%I FOR ALL TO authenticated USING (public.go_pode(''edit'')) WITH CHECK (public.go_pode(''edit''))', t);
    END IF;
  END LOOP;
END $$;
